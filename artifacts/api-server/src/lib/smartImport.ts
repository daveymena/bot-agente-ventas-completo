// @ts-nocheck
import OpenAI from "openai";
import { logger } from "./logger";
import { createAIClient, getProviderConfig } from "@workspace/integrations-openai-ai-server";

export interface ColumnMapping {
  name: string;
  description: string;
  price: string;
  currency: string;
  category?: string;
  imageUrl?: string;
  [key: string]: string | undefined;
}

export async function getSmartColumnMapping(headers: string[], sampleRows: any[]): Promise<ColumnMapping> {
  const nvidiaConfig = getProviderConfig("nvidia");
  if (!nvidiaConfig) {
    logger.warn("[SmartImport] NVIDIA config not found, using default mapping");
    return { name: headers[0], description: headers[1], price: headers[2], currency: "USD" };
  }

  const client = createAIClient(nvidiaConfig);
  const prompt = `
Actúa como un experto en estructuración de datos para una plataforma SaaS.
Tengo un archivo con las siguientes cabeceras: [${headers.join(", ")}]
Y estas son las primeras filas de ejemplo: ${JSON.stringify(sampleRows)}

Tu tarea es mapear estas cabeceras a los campos de mi base de datos:
- name (Nombre del producto)
- description (Descripción detallada)
- price (Precio numérico)
- currency (Moneda, ej: COP, USD)
- category (Categoría)
- imageUrl (URL de la imagen)

Responde ÚNICAMENTE con un objeto JSON donde la llave es el campo de mi base de datos y el valor es el nombre EXACTO de la cabecera del archivo.
Ejemplo: {"name": "Articulo", "price": "Valor Unitario", ...}
`;

  try {
    const response = await client.chat.completions.create({
      model: nvidiaConfig.model,
      messages: [{ role: "system", content: prompt }],
      temperature: 0,
      response_format: { type: "json_object" }
    });

    const mapping = JSON.parse(response.choices[0]?.message?.content || "{}");
    logger.info({ mapping }, "[SmartImport] Mapping generated by Kimi 2.6");
    return mapping;
  } catch (error) {
    logger.error({ error }, "[SmartImport] Failed to get mapping from AI");
    return { name: headers[0], description: headers[1], price: headers[2], currency: "USD" };
  }
}

export function processRowsWithMapping(rows: any[], mapping: ColumnMapping) {
  return rows.map(row => ({
    name: String(row[mapping.name] || "Sin nombre"),
    description: String(row[mapping.description] || ""),
    price: parseFloat(String(row[mapping.price] || "0").replace(/[^0-9.]/g, "")) || 0,
    currency: String(row[mapping.currency] || "USD"),
    category: mapping.category ? String(row[mapping.category] || "") : null,
    imageUrl: mapping.imageUrl ? String(row[mapping.imageUrl] || "") : null,
  }));
}
