const MAP = new Map<string, string[]>();
for (const [k, v] of PAIRS) MAP.set(k, v);

export function stripDiacritics(s: string) {
  return s.normalize("NFD").replace(/[\u0300-\u036f]/g, "").replace(/ñ/g, "n");
}

export function synonymsFor(term: string): string[] {
  const t = stripDiacritics(term.toLowerCase());
  const direct = MAP.get(t) || [];
  // Inversa: entradas cuya traducción principal (primer sinónimo) es este término.
  // Si el término no tiene entrada propia (p. ej. una palabra en inglés) también
  // aceptamos el segundo puesto, para que "mug" llegue a "taza" sin que
  // "noche" arrastre a "estrellas", "luna" y "neón".
  const depth = direct.length ? 1 : 2;
  const inverse: string[] = [];
  for (const [k, v] of PAIRS) if (v.slice(0, depth).some((x) => stripDiacritics(x) === t)) inverse.push(k);
  return [...new Set([...direct, ...inverse])].filter((x) => stripDiacritics(x) !== t).slice(0, 6);
}
