/**
 * SCRIPT DE DIAGNÓSTICO AUTOMÁTICO
 * Verifica la conexión entre frontend y backend
 */

const http = require('http');

const colors = {
  reset: '\x1b[0m',
  green: '\x1b[32m',
  red: '\x1b[31m',
  yellow: '\x1b[33m',
  blue: '\x1b[34m',
  magenta: '\x1b[35m'
};

function log(message, color = 'reset') {
  console.log(`${colors[color]}${message}${colors.reset}`);
}

async function testEndpoint(port, path, name) {
  return new Promise((resolve) => {
    const options = {
      hostname: 'localhost',
      port: port,
      path: path,
      method: 'GET',
      timeout: 3000
    };

    const req = http.request(options, (res) => {
      let data = '';
      res.on('data', (chunk) => { data += chunk; });
      res.on('end', () => {
        if (res.statusCode === 200) {
          log(`✅ ${name} - OK (puerto ${port})`, 'green');
          try {
            const json = JSON.parse(data);
            log(`   Respuesta: ${JSON.stringify(json).substring(0, 100)}...`, 'blue');
          } catch (e) {
            log(`   Respuesta: ${data.substring(0, 100)}...`, 'blue');
          }
          resolve({ success: true, port, path, name });
        } else {
          log(`⚠️ ${name} - Status ${res.statusCode} (puerto ${port})`, 'yellow');
          resolve({ success: false, port, path, name, error: `Status ${res.statusCode}` });
        }
      });
    });

    req.on('error', (error) => {
      log(`❌ ${name} - ERROR: ${error.message} (puerto ${port})`, 'red');
      resolve({ success: false, port, path, name, error: error.message });
    });

    req.on('timeout', () => {
      req.destroy();
      log(`❌ ${name} - TIMEOUT (puerto ${port})`, 'red');
      resolve({ success: false, port, path, name, error: 'Timeout' });
    });

    req.end();
  });
}

async function runDiagnostics() {
  log('\n🔍 DIAGNÓSTICO AUTOMÁTICO - FRONTEND Y BACKEND\n', 'magenta');
  log('═'.repeat(60), 'blue');

  // Puertos comunes del backend
  const backendPorts = [3000, 3001, 3002, 5000, 8000];
  
  log('\n📡 PASO 1: Buscando el backend...\n', 'yellow');
  
  const backendTests = [];
  for (const port of backendPorts) {
    backendTests.push(testEndpoint(port, '/api/whatsapp/status', `Backend WhatsApp`));
    backendTests.push(testEndpoint(port, '/api/code-agent/current', `Backend Arquitecto`));
  }
  
  const backendResults = await Promise.all(backendTests);
  const successfulBackends = backendResults.filter(r => r.success);
  
  if (successfulBackends.length > 0) {
    const backendPort = successfulBackends[0].port;
    log(`\n✅ BACKEND ENCONTRADO EN PUERTO ${backendPort}\n`, 'green');
    
    // Verificar todos los endpoints en el puerto correcto
    log('📡 PASO 2: Verificando endpoints del backend...\n', 'yellow');
    
    const endpoints = [
      { path: '/api/whatsapp/status', name: 'WhatsApp Status' },
      { path: '/api/code-agent/current', name: 'Arquitecto Current' },
    ];
    
    for (const endpoint of endpoints) {
      await testEndpoint(backendPort, endpoint.path, endpoint.name);
    }
    
    // Generar recomendaciones
    log('\n📝 RECOMENDACIONES:\n', 'magenta');
    log(`1. El backend está corriendo en el puerto ${backendPort}`, 'blue');
    log(`2. Asegúrate de que el frontend tenga configurado:`, 'blue');
    log(`   VITE_API_URL=http://localhost:${backendPort}`, 'green');
    log(`3. O actualiza vite.config.ts:`, 'blue');
    log(`   proxy: { "/api": { target: "http://localhost:${backendPort}" } }`, 'green');
    
    // Crear archivo .env automáticamente
    const fs = require('fs');
    const path = require('path');
    const envPath = path.join(__dirname, 'artifacts', 'ventas-pro', '.env');
    const envContent = `# Auto-generated by test-conexion.js\nVITE_API_URL=http://localhost:${backendPort}\n`;
    
    try {
      fs.writeFileSync(envPath, envContent);
      log(`\n✅ Archivo .env creado automáticamente en:`, 'green');
      log(`   ${envPath}`, 'blue');
      log(`\n🔄 REINICIA EL FRONTEND para aplicar los cambios:`, 'yellow');
      log(`   cd artifacts/ventas-pro && npm run dev`, 'green');
    } catch (e) {
      log(`\n⚠️ No se pudo crear el archivo .env automáticamente`, 'yellow');
      log(`   Créalo manualmente en: artifacts/ventas-pro/.env`, 'blue');
      log(`   Con el contenido: VITE_API_URL=http://localhost:${backendPort}`, 'green');
    }
    
  } else {
    log('\n❌ BACKEND NO ENCONTRADO\n', 'red');
    log('El backend NO está corriendo en ningún puerto común.', 'yellow');
    log('\n📝 SOLUCIÓN:', 'magenta');
    log('1. Inicia el backend:', 'blue');
    log('   cd artifacts/api-server', 'green');
    log('   npm run dev', 'green');
    log('\n2. Luego vuelve a ejecutar este script:', 'blue');
    log('   node test-conexion.js', 'green');
  }
  
  log('\n═'.repeat(60), 'blue');
  log('\n✅ DIAGNÓSTICO COMPLETO\n', 'magenta');
}

// Ejecutar diagnóstico
runDiagnostics().catch(console.error);
